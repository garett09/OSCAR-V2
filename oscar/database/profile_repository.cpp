/*
 * Resolve a portable profile path
 *
 * Parameters:
 *   portablePath - Path that may contain %PROFDIR% variable
 *   profilesBasePath - Base path for profiles directory
 *
 * Returns: Resolved absolute path
 *
 * This static method replaces %PROFDIR% with the actual profiles base path,
 * making the database portable across different machines and installations.
 *
 * Example:
 *   Input:  "%PROFDIR%/John"
 *   Base:   "C:/Users/Guy/Documents/OSCAR20_Data/Profiles"
 *   Output: "C:/Users/Guy/Documents/OSCAR20_Data/Profiles/John"
 *
 * Normalisation is delegated to QDir::cleanPath(), which converts native
 * separators to '/' and collapses redundant slashes while preserving the
 * leading "//" of a UNC path on platforms that support them.  A data folder
 * on a Windows network share resolves to "//server/share/...", and stripping
 * that second leading slash would leave a path that cannot be opened.
 */
QString ProfileRepository::resolvePath(const QString& portablePath, const QString& profilesBasePath)
{
    QString resolved = portablePath;

    // Replace %PROFDIR% with actual base path
    if (resolved.contains("%PROFDIR%")) {
        resolved.replace("%PROFDIR%", profilesBasePath);
    }

    return QDir::cleanPath(resolved);
}

/*
 * Convert QSqlQuery result to ProfileData
 *
 * Parameters:
 *   query - Query positioned at a result row
 *
 * Returns: ProfileData populated from current row
 *
 * Expected column order: id, username, data_folder, status, status_changed_at, created_at, updated_at
 */
ProfileData ProfileRepository::recordToData(QSqlQuery& query)
{
    ProfileData data;
    
    data.id = query.value(0).toLongLong();
    data.username = query.value(1).toString();
    data.dataFolder = query.value(2).toString();
    data.status = query.value(3).toString();
    data.statusChangedAt = query.value(4).toString();
    data.createdAt = query.value(5).toString();
    data.updatedAt = query.value(6).toString();
    
    return data;
}
