/*
 * Get the database connection from DatabaseManager
 *
 * Returns: QSqlDatabase instance
 */
QSqlDatabase ProfileRepository::database()
{
    return DatabaseManager::instance().database();
}

/*
 * Create a new profile in the database
 *
 * Parameters:
 *   data - ProfileData containing username and dataFolder
 *
 * Returns: Profile ID if successful, -1 on error
 *
 * The id field in data is ignored (auto-generated by database).
 * Timestamps are set automatically by the database.
 */
qint64 ProfileRepository::create(const ProfileData& data)
{
    QSqlQuery query(database());
    
    query.prepare(
        "INSERT INTO profiles (username, data_folder) "
        "VALUES (:username, :data_folder)"
    );
    
    query.bindValue(":username", data.username);
    query.bindValue(":data_folder", data.dataFolder);
    
    if (!query.exec()) {
        qWarning() << "ProfileRepository::create() failed:" << query.lastError().text();
        DatabaseManager::instance().checkQueryError("ProfileRepository::create", query);
        return -1;
    }

    qint64 id = query.lastInsertId().toLongLong();
    qDebug() << "ProfileRepository: Created profile" << data.username << "with id" << id;
    
    return id;
}

/*
 * Find a profile by database ID
 *
 * Parameters:
 *   id - Database primary key
 *
 * Returns: ProfileData if found, or null ProfileData (id=0) if not found
 */
ProfileData ProfileRepository::findById(qint64 id)
{
    QSqlQuery query(database());
    
    query.prepare(
        "SELECT id, username, data_folder, status, status_changed_at, created_at, updated_at "
        "FROM profiles WHERE id = :id"
    );
    
    query.bindValue(":id", id);
    
    if (!query.exec()) {
        qWarning() << "ProfileRepository::findById() failed:" << query.lastError().text();
        DatabaseManager::instance().checkQueryError("ProfileRepository::findById", query);
        return ProfileData();
    }
    
    if (query.next()) {
        return recordToData(query);
    }
    
    return ProfileData();
}

